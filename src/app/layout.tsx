import { Bricolage_Grotesque, Inter, Manrope } from 'next/font/google';
import { Analytics } from '@vercel/analytics/react';
import type { CSSProperties } from 'react';
import type { Metadata, Viewport } from 'next';
import { Header } from '@/components/layout/Header';
import { Footer } from '@/components/layout/Footer';
import { MobileCtaBar } from '@/components/layout/MobileCtaBar';
import { PostHogProvider } from '@/components/layout/PostHogProvider';
import { ScrollDepthTracker } from '@/components/layout/ScrollDepthTracker';
import { CookieConsent } from '@/components/layout/CookieConsent';
import { JsonLd } from '@/components/layout/JsonLd';
import { SITE_URL, THEME_COLOR } from '@/lib/constants';
import { withBasePath } from '@/lib/paths';
import { createMetadata, mobileApplicationSchema, organizationSchema } from '@/lib/seo';
import './globals.css';

/*
 * Fonts (docs/landing-decisions.md D4): Manrope, Inter and Bricolage Grotesque, across the whole site.
 * Manrope is the only one preloaded (it carries every heading and paragraph). Inter is the card UI text in the hero
 * mock-ups; Bricolage is the wordmark only. All are variable fonts, latin subset, display swap, with size-adjusted
 * fallbacks generated by next/font so the swap does not shift layout.
 */
const manrope = Manrope({
  variable: '--font-manrope',
  subsets: ['latin'],
  display: 'swap',
});

const inter = Inter({
  variable: '--font-inter',
  subsets: ['latin'],
  display: 'swap',
  preload: false,
});

const bricolage = Bricolage_Grotesque({
  variable: '--font-bricolage',
  subsets: ['latin'],
  display: 'swap',
  preload: false,
});

export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  ...createMetadata({
    title: 'CheckApp: your daily wellness companion. Meet DiDi.',
    description:
      'CheckApp turns checking in on your health into a small daily habit. DiDi looks at what you share and tells you what it notices in plain language. A wellness companion, not a medical device.',
    path: '/',
  }),
  other: { yandex: 'noindex, nofollow' },
};

export const viewport: Viewport = {
  themeColor: THEME_COLOR,
  colorScheme: 'dark',
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // CSS url() ignores GITHUB_PAGES_BASE_PATH, so art that CSS references is published as custom properties from here.
  const assetVars = {
    '--noise-url': `url("${withBasePath('/landing/_shared/noise-128.png')}")`,
  } as CSSProperties;

  return (
    <html lang="en" className={`${manrope.variable} ${inter.variable} ${bricolage.variable}`} style={assetVars}>
      <body className="font-sans antialiased">
        <JsonLd data={[organizationSchema(), mobileApplicationSchema()]} />
        <a href="#main" className="skip-link">
          Skip to content
        </a>
        <Header />
        <main id="main">{children}</main>
        <Footer />
        <MobileCtaBar />
        <PostHogProvider />
        <ScrollDepthTracker />
        {/* Vercel Analytics: a no-op off Vercel (GitHub Pages, local). */}
        <Analytics />
        <CookieConsent />
      </body>
    </html>
  );
}
